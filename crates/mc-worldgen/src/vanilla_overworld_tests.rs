//! Observed 26.1.2 fixtures from the headless vanilla RandomState/chunk generator.
use crate::{TerrainGenerator, vanilla_climate::VanillaClimate};
use mc_data::Identifier;
use mc_world::{BlockRegistry, ChunkGenerator, ChunkPos};
use std::{path::PathBuf, sync::Arc};

fn content_cache() -> Option<PathBuf> {
    let root = std::env::var_os("SOLARIS_CONTENT_CACHE")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../data/vanilla"));
    if root
        .join("data/minecraft/worldgen/noise_settings/overworld.json")
        .is_file()
    {
        Some(root)
    } else {
        eprintln!(
            "SKIP vanilla overworld fixtures: export local bootstrap worldgen data with tools/extract-vanilla-worldgen.sh"
        );
        None
    }
}

#[test]
fn vanilla_three_seed_climate_and_height_fixtures() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    // Fixtures are independently observed native results, not values generated by Solaris.
    for (seed, fixtures) in [
        (
            0,
            [
                (0, 0, 55, "river", [1182, -13, -81, -1039, -881, 111]),
                (-128, 128, 60, "forest", [1190, -186, -35, -513, -82, 1279]),
                (
                    2048,
                    -2048,
                    66,
                    "savanna",
                    [4168, -2854, 967, 2334, 227, -4437],
                ),
            ],
        ),
        (
            81,
            [
                (
                    0,
                    0,
                    49,
                    "cold_ocean",
                    [-3210, -1132, -3768, -4529, -1237, -4628],
                ),
                (
                    -128,
                    128,
                    47,
                    "cold_ocean",
                    [-3665, -3203, -3174, -2879, -1237, -407],
                ),
                (
                    2048,
                    -2048,
                    66,
                    "savanna",
                    [3100, -1708, 4824, 2220, 16, 1263],
                ),
            ],
        ),
        (
            497625,
            [
                (
                    0,
                    0,
                    72,
                    "birch_forest",
                    [1141, 1339, -1500, -978, 582, -5630],
                ),
                (
                    -128,
                    128,
                    97,
                    "birch_forest",
                    [995, 1320, 1024, -897, 2773, -6706],
                ),
                (
                    2048,
                    -2048,
                    65,
                    "dark_forest",
                    [740, 4427, 1083, 570, 67, 2964],
                ),
            ],
        ),
    ] {
        let climate = VanillaClimate::new(seed as u64, &root).unwrap();
        let mut terrain = TerrainGenerator::new(seed, blocks.clone());
        terrain.load_vanilla_worldgen(&root).unwrap();
        for (x, z, height, biome, target) in fixtures {
            let sample = climate.sample(x, 64, z);
            assert_eq!(sample.quantized, target, "seed {seed}, ({x},64,{z})");
            assert_eq!(
                sample.biome,
                format!("minecraft:{biome}"),
                "seed {seed}, ({x},64,{z})"
            );
            assert_eq!(
                terrain.surface_height(x, z),
                height,
                "seed {seed}, ({x},{z})"
            );
            assert_eq!(terrain.noise_biome(x, 64, z).as_str(), sample.biome);
        }
    }
}

/// Every chunk biome cell and every column's surface biome is the noise
/// biome at its own position, whatever order generation samples them in.
#[test]
fn generated_biomes_are_noise_biomes_at_their_cells() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    let mut terrain = TerrainGenerator::new(712816, blocks);
    terrain.load_vanilla_worldgen(&root).unwrap();
    for pos in [
        ChunkPos { x: 0, z: 0 },
        ChunkPos { x: -3, z: 5 },
        ChunkPos { x: 40, z: -17 },
    ] {
        let chunk = terrain.generate(pos);
        let min_y = chunk.geometry().min_y();
        for (section, biomes) in chunk.biomes.iter().enumerate() {
            for cell in 0..64u8 {
                let (cx, cy, cz) = (cell % 4, cell / 16, cell / 4 % 4);
                let x = pos.x * 16 + i32::from(cx) * 4 + 2;
                let y = min_y + section as i32 * 16 + i32::from(cy) * 4 + 2;
                let z = pos.z * 16 + i32::from(cz) * 4 + 2;
                assert_eq!(
                    biomes.get(cx, cy, cz),
                    &terrain.noise_biome(x, y, z),
                    "({x},{y},{z})"
                );
            }
        }
        for column in 0..256 {
            let x = pos.x * 16 + column % 16;
            let z = pos.z * 16 + column / 16;
            let sample = terrain.diagnostic_sample(x, z);
            assert_eq!(
                sample.biome,
                terrain.noise_biome(x, sample.surface_y, z),
                "({x},{z})"
            );
        }
    }
}

#[test]
fn vanilla_density_height_and_ocean_water_reach_generated_blocks() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    let water = blocks
        .block(&Identifier::parse("minecraft:water").unwrap())
        .unwrap()
        .default;
    let air = blocks
        .block(&Identifier::parse("minecraft:air").unwrap())
        .unwrap()
        .default;
    let mut terrain = TerrainGenerator::new(81, blocks);
    terrain.load_vanilla_worldgen(&root).unwrap();
    let chunk = terrain.generate(ChunkPos { x: 0, z: 0 });
    let top = 49; // Native OCEAN_FLOOR_WG top at seed81 block(0,0).
    assert_ne!(chunk.get_block(0, top, 0), Some(air));
    assert_eq!(chunk.get_block(0, top + 1, 0), Some(water));
    assert_eq!(chunk.get_block(0, 62, 0), Some(water));
    assert_eq!(chunk.get_block(0, 63, 0), Some(air));
}

#[test]
fn vanilla_chunk_density_matches_columns_at_cells_and_negative_borders() {
    let Some(root) = content_cache() else { return };
    for seed in [0, 81, 497625] {
        let density = crate::vanilla_density::VanillaDensity::new(seed, &root).unwrap();
        let mut chunk = vec![0.0; density.height() as usize * 256];
        let mut column = vec![0.0; density.height() as usize];
        // The unaligned square crosses six lattice points on each axis, rather
        // than the usual five. Each column independently evaluates its corners.
        for (min_x, min_z) in [(0, 0), (-16, -16), (192, -448), (-7, 5)] {
            density.fill_density_chunk(min_x, min_z, &mut chunk);
            for z in 0..16 {
                for x in 0..16 {
                    density.fill_density_column(min_x + x, min_z + z, &mut column);
                    for (y, expected) in column.iter().enumerate() {
                        assert_eq!(
                            chunk[y * 256 + z as usize * 16 + x as usize].to_bits(),
                            expected.to_bits(),
                            "seed {seed}, ({},{},{})",
                            min_x + x,
                            density.min_y() + y as i32,
                            min_z + z,
                        );
                    }
                }
            }
        }
    }
}

#[test]
fn vanilla_halo_surface_heights_match_independent_queries() {
    let Some(root) = content_cache() else { return };
    for seed in [0, 81, 497625] {
        let density = crate::vanilla_density::VanillaDensity::new(seed, &root).unwrap();
        let mut sampler = density.surface_height_sampler(-25, -9, 8, 24);
        // Reverse alternating rows to exercise reuse across cells and negative
        // quart boundaries, independently of the generator's visitation order.
        for z in -9..=24 {
            for offset in 0..34 {
                let x = if z % 2 == 0 { -25 + offset } else { 8 - offset };
                assert_eq!(
                    sampler.surface_height(x, z),
                    density.surface_height(x, z),
                    "seed {seed}, ({x},{z})",
                );
            }
        }
        // A bounded cache miss must remain an exact query, not clamp a column.
        for (x, z) in [(-129, 128), (192, -448), (-25, -9), (8, 24)] {
            assert_eq!(
                sampler.surface_height(x, z),
                density.surface_height(x, z),
                "seed {seed}, ({x},{z}) after halo",
            );
        }
    }
}

/// The far-terrain LOD surface is the generated density surface without caves:
/// on lattice columns it is never below the full surface (caves only remove
/// blocks) and equals it wherever no cave reaches the top.
#[test]
fn lod_surface_is_the_density_surface_without_caves() {
    let Some(root) = content_cache() else { return };
    let density = crate::vanilla_density::VanillaDensity::new(81, &root).unwrap();
    let (mut equal, mut total) = (0u32, 0u32);
    let (mut lod_time, mut full_time) = (std::time::Duration::ZERO, std::time::Duration::ZERO);
    for z in (-4096..4096).step_by(512) {
        for x in (-4096..4096).step_by(512) {
            let started = std::time::Instant::now();
            let lod = density
                .lod_surface_height(x, z)
                .expect("vanilla router has a LOD surface");
            lod_time += started.elapsed();
            let started = std::time::Instant::now();
            let full = density.surface_height(x, z);
            full_time += started.elapsed();
            assert!(lod >= full, "({x},{z}): lod {lod} below generated {full}");
            equal += u32::from(lod == full);
            total += 1;
        }
    }
    eprintln!(
        "lod surface: {equal}/{total} columns equal; per column lod {:?}, full {:?}",
        lod_time / total,
        full_time / total,
    );
    // Cave carves (entrance min-branch, noodles, spaghetti) legitimately
    // lower the generated surface: seed 81 measures 226/256 equal on this
    // grid. The hard invariant is `lod >= full` above; the ratio only
    // tripwires a broken LOD field (wrong branch, missing slide), which would
    // mismatch nearly every column.
    assert!(equal * 20 >= total * 17, "{equal}/{total} equal");
}

/// The far-terrain program carries no seed and stays small. With
/// `SOLARIS_LOD_PROGRAM_FIXTURE=<path>` it also writes the program and the
/// server's `lod_column` answers for a column grid (zlib: `u32` program
/// length, program, `u32` count, then `i32 x, i32 z, i32 height, u16` biome
/// length and name), the native client's parity fixture.
#[test]
fn lod_program_exports_without_the_seed() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    let seed = 81i64;
    let mut terrain = TerrainGenerator::new(seed, blocks);
    terrain.load_vanilla_worldgen(&root).unwrap();
    let program = terrain.lod_program().unwrap().expect("vanilla LOD program");
    assert_eq!(&program[..4], b"SLOD");
    assert_eq!(
        u16::from_le_bytes([program[4], program[5]]),
        crate::vanilla_density::program::PROGRAM_VERSION
    );
    let seed_bytes = [seed.to_le_bytes(), seed.to_be_bytes()];
    // The encoder never writes the seed: the header is world geometry and
    // table counts, the body is noise tables, code and biome rows. A raw
    // 8-byte window scan false-positives once the octave table holds more
    // than 81 entries (octave index 81 followed by an amplitude low word
    // reads as `81i64` across the field boundary), so the tripwire covers
    // the fixed-size header where a seed field would live.
    assert!(program.len() >= 26);
    for needle in seed_bytes {
        assert!(
            !program[..26].windows(8).any(|window| window == needle),
            "the level seed must not appear in the program header"
        );
    }
    assert!(program.len() < 512 * 1024, "{} bytes", program.len());
    let Some(path) = std::env::var_os("SOLARIS_LOD_PROGRAM_FIXTURE") else {
        return;
    };
    let mut fixture = Vec::new();
    fixture.extend((program.len() as u32).to_le_bytes());
    fixture.extend(&program);
    let columns: Vec<(i32, i32)> = (-6..6)
        .flat_map(|z| (-6..6).map(move |x| (x * 1373 + 7, z * 1291 - 3)))
        .chain([(0, 0), (-1, -1), (8191, -8192), (2, 6)])
        .collect();
    fixture.extend((columns.len() as u32).to_le_bytes());
    for (x, z) in columns {
        let (height, biome) = terrain.lod_column(x, z);
        let name = biome.to_string();
        for value in [x, z, height] {
            fixture.extend(value.to_le_bytes());
        }
        fixture.extend((name.len() as u16).to_le_bytes());
        fixture.extend(name.as_bytes());
    }
    let mut encoder = flate2::write::ZlibEncoder::new(Vec::new(), flate2::Compression::best());
    std::io::Write::write_all(&mut encoder, &fixture).unwrap();
    std::fs::write(&path, encoder.finish().unwrap()).unwrap();
    eprintln!("program {} bytes, fixture written", program.len());
}
